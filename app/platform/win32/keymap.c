/* Windows scan codes (set 1) and virtual keys -> USB HID usages. */
#include "capture.h"

/* Non-extended scan codes 0x00..0x58. */
static const uint8_t BASE[0x59] = {
    0, 0x29, 0x1e, 0x1f, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x2d, 0x2e, 0x2a, 0x2b,
    0x14, 0x1a, 0x08, 0x15, 0x17, 0x1c, 0x18, 0x0c, 0x12, 0x13, 0x2f, 0x30, 0x28, 0xe0, 0x04, 0x16,
    0x07, 0x09, 0x0a, 0x0b, 0x0d, 0x0e, 0x0f, 0x33, 0x34, 0x35, 0xe1, 0x31, 0x1d, 0x1b, 0x06, 0x19,
    0x05, 0x11, 0x10, 0x36, 0x37, 0x38, 0xe5, 0x55, 0xe2, 0x2c, 0x39, 0x3a, 0x3b, 0x3c, 0x3d, 0x3e,
    0x3f, 0x40, 0x41, 0x42, 0x43, 0x53, 0x47, 0x5f, 0x60, 0x61, 0x56, 0x5c, 0x5d, 0x5e, 0x57, 0x59,
    0x5a, 0x5b, 0x62, 0x63, 0x46, 0, 0x64, 0x44, 0x45,
};

static uint8_t extended(DWORD scan)
{
    switch (scan) {
    case 0x1c: return 0x58; /* keypad Enter */
    case 0x1d: return 0xe4; /* right Ctrl */
    case 0x35: return 0x54; /* keypad / */
    case 0x37: return 0x46; /* Print Screen */
    case 0x38: return 0xe6; /* right Alt / AltGr */
    case 0x47: return 0x4a; case 0x48: return 0x52; case 0x49: return 0x4b;
    case 0x4b: return 0x50; case 0x4d: return 0x4f; case 0x4f: return 0x4d;
    case 0x50: return 0x51; case 0x51: return 0x4e; case 0x52: return 0x49; case 0x53: return 0x4c;
    case 0x5b: return 0xe3; /* left Windows */
    case 0x5c: return 0xe7; /* right Windows */
    case 0x5d: return 0x65; /* Menu */
    default: return 0;
    }
}

uint16_t win_scancode_to_hid(DWORD scan, bool ext, DWORD vk)
{
    if (vk == VK_PAUSE) return 0x48;
    if (vk == VK_NUMLOCK) return 0x53;
    if (vk >= VK_F13 && vk <= VK_F24) return (uint16_t)(0x68 + (vk - VK_F13));
    if (vk == VK_RSHIFT) return 0xe5;
    if (ext) return extended(scan);
    return scan < sizeof(BASE) ? BASE[scan] : 0;
}

uint16_t win_vk_to_consumer(DWORD vk)
{
    switch (vk) {
    case VK_MEDIA_PLAY_PAUSE: return 0x00cd;
    case VK_MEDIA_NEXT_TRACK: return 0x00b5;
    case VK_MEDIA_PREV_TRACK: return 0x00b6;
    case VK_MEDIA_STOP: return 0x00b7;
    case VK_VOLUME_MUTE: return 0x00e2;
    case VK_VOLUME_UP: return 0x00e9;
    case VK_VOLUME_DOWN: return 0x00ea;
    case VK_BROWSER_BACK: return 0x0224;
    case VK_BROWSER_FORWARD: return 0x0225;
    case VK_BROWSER_REFRESH: return 0x0227;
    case VK_BROWSER_SEARCH: return 0x0221;
    case VK_BROWSER_HOME: return 0x0223;
    case VK_LAUNCH_MAIL: return 0x018a;
    case VK_LAUNCH_APP2: return 0x0192; /* calculator */
    default: return 0;
    }
}

uint8_t win_vk_to_system(DWORD vk)
{
    return vk == VK_SLEEP ? 2 : 0;
}
