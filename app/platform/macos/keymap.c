uint16_t mac_keycode_to_hid(uint16_t kvk)
{
    return kvk < sizeof(KVK) ? KVK[kvk] : 0;
}

/* NX_KEYTYPE_* (media keys sent as system-defined events) -> HID consumer usages. */
uint16_t mac_nxkey_to_consumer(int nxkey)
{
    switch (nxkey) {
    case 0: return 0x00E9;  /* volume up */
    case 1: return 0x00EA;  /* volume down */
    case 7: return 0x00E2;  /* mute */
    case 16: return 0x00CD; /* play/pause */
    case 17: return 0x00B5; /* next track */
    case 18: return 0x00B6; /* previous track */
    default: return 0;
    }
}
